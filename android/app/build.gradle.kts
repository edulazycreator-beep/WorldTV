    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = file(releaseStoreFile!!)
                storePassword = signingValue("WORLDTV_KEYSTORE_PASSWORD", "storePassword")
                keyAlias = signingValue("WORLDTV_KEY_ALIAS", "keyAlias")
                keyPassword = signingValue("WORLDTV_KEY_PASSWORD", "keyPassword")
            }
